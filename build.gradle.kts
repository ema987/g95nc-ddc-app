// Keep in sync with AppInfo.NAME in src/main/kotlin/.../AppInfo.kt - this build script and the
// app's own Kotlin sources are separate compilation units.
val appDisplayName = "G95NC Controller"

// The git tag is the single source of truth for the version: the release workflow passes
// -PappVersion=1.2.3 for tag v1.2.3. Local/untagged builds show "dev" in the app, but installers
// still need a plain numeric MAJOR.MINOR.PATCH (MAJOR > 0 on macOS), hence the separate fallback.
val appVersion: String? = providers.gradleProperty("appVersion").orNull
val displayVersion = appVersion ?: "dev"
val installerVersion = appVersion ?: "1.0.0"

// Exposes the version to the app as AppVersion.kt, so AppInfo.VERSION never needs a hand edit.
val generateAppVersion by tasks.registering {
    val outputDir = layout.buildDirectory.dir("generated/appVersion/kotlin")
    val version = displayVersion
    inputs.property("version", version)
    outputs.dir(outputDir)
    doLast {
        val file = outputDir.get().file("com/g95nc/controller/AppVersion.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            "// Generated by build.gradle.kts from -PappVersion - do not edit.\n" +
                "package com.g95nc.controller\n\n" +
                "internal const val APP_VERSION = \"$version\"\n"
        )
    }
}

compose.desktop {
    application {
        mainClass = "com.g95nc.controller.MainKt"
        nativeDistributions {
            targetFormats(org.jetbrains.compose.desktop.application.dsl.TargetFormat.Dmg, org.jetbrains.compose.desktop.application.dsl.TargetFormat.Msi, org.jetbrains.compose.desktop.application.dsl.TargetFormat.Deb, org.jetbrains.compose.desktop.application.dsl.TargetFormat.Rpm)
            // This becomes jpackage's --name: the actual .app bundle folder name (which is what
            // Finder/Spotlight/Dock display - CFBundleDisplayName does NOT override it, despite
            // documentation suggesting otherwise; confirmed by inspecting the real jpackage
            // invocation Gradle builds, not just reading the DSL). Also the Start Menu/taskbar
            // name on Windows. A space here is fine on both platforms.
            packageName = appDisplayName
            packageVersion = installerVersion

            macOS {
                // NOT the same as the top-level packageName above despite the identical property
                // name on this nested type - this one maps to jpackage's --mac-package-name,
                // which only sets CFBundleDisplayName (a real field, just not the one Finder
                // reads for its label). Set anyway since it's free and correct.
                packageName = appDisplayName
                dockName = appDisplayName
                bundleID = "com.g95nc.controller"
                iconFile.set(project.file("packaging/icon.icns"))
            }
            linux {
                // Linux's own packageName maps to --linux-package-name - the Debian control
                // file's "Package:" field, which must be lowercase/no-spaces unlike the
                // human-readable top-level name above.
                packageName = "g95nc-ddc-app"
                iconFile.set(project.file("packaging/icon.png"))
            }
            windows {
                iconFile.set(project.file("packaging/icon.ico"))
                // Without these jpackage installs the app with no Start Menu entry at all.
                menu = true
                shortcut = true
                // Fixed forever so installing a newer .msi upgrades in place instead of adding a
                // second copy side by side - never change this once releases are out.
                upgradeUuid = "DF280EEE-7857-4C74-B246-F13039666607"
            }
            // Untested on an actual Windows machine (built here on macOS with ImageMagick, no
            // Windows box available) - see packaging/README.md.
        }
    }
}

